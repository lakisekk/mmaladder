    d.fights = Array.isArray(d.fights) ? d.fights : [];
    d.history = Array.isArray(d.history) ? d.history : [];
    d.settings = Object.assign({ p4pPublic: false, siteUrl: "", domain: "", analyticsType: "", analyticsId: "" }, d.settings || {});
